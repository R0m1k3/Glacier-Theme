#!/usr/bin/env python3
"""Writes test/pages/apps-search.html: the search bar Community Applications 2026.07.21 (the version
Unraid 7.3 installs, github.com/unraid/community.applications, archive/*.txz) puts above its pages
(skins/Narrow/skin.html, moved after #menu by Apps.page), after a DockerHub search: search box,
"Results Per Page", the DockerHub and Apps buttons and the category line. The page carries CA's
own stylesheets (colors, main, responsive, then the white theme; the black theme's variables
under .Theme--black for the dark render) and reuses the cards of apps-home-wrapped.

    python3 test/tools/ca-search.py /path/to/usr/local/emhttp/plugins/community.applications
"""
import re
import sys
from pathlib import Path

ca = Path(sys.argv[1])
skin = ca / 'skins/Narrow'
css = '\n'.join((skin / f).read_text() for f in (
    'styles/community.applications.colors.css',
    'styles/community.applications.css',
    'styles/community.applications.responsive.css',
    'themes/white.css',
))
black_vars = re.search(r':root\s*\{(.*?)\}', (skin / 'themes/black.css').read_text(), re.S).group(1)
css += '\n.Theme--black {%s}\n' % black_vars

out = Path(__file__).resolve().parent.parent / 'pages/apps-search.html'
out.write_text(f"""page: Apps
active: Apps
include: apps-home-wrapped
---
<!-- Generated by test/tools/ca-search.py: Community Applications 2026.07.21's search bar
     (skins/Narrow/skin.html) after a DockerHub search, with CA's own stylesheets. -->
<style>
{css}
</style>
<div class="searchAreaHolder menuAdjust">
  <div class='searchArea onlyShowWithFeed'>
    <div class='mobileMenuButton'>
      <div class='showMenuButton menuAdjust menuHidden' title="Afficher le menu"></div>
      <div class='closeMenuButton menuAdjust menuHidden' title="Fermer le menu"></div>
    </div>
    <div id='searchFilter' class='hideWithMenu'>
      <div class="awesomplete"><input type='text' id='searchBox' placeholder='Recherche' autocomplete="off" aria-expanded="false" aria-owns="awesomplete_list_1" role="combobox"><ul hidden="" role="listbox" id="awesomplete_list_1"></ul><span class="visually-hidden" role="status" aria-live="assertive" aria-atomic="true"></span></div>
      <span class='searchSubmit'><i id='searchButton' class='fa fa-search fa-lg'></i></span>
    </div>
    <div class='caButton maxPerPage hideWithMenu' id='maxPerPage'>Results Per Page: 99999</div>
    <div class='dockerSearch caButton hideWithMenu' title="Search dockerHub for more containers">DockerHub</div>
    <div class='templateSearch caButton hideWithMenu' title="Search for applications from">Applis</div>
    <div class='category categoryLine hideWithMenu'>DockerHub Search for plex <span id='pageNumber'></span></div>
    <div class='category altCategoryLine hideWithMenu'>DockerHub Search for plex <span id='pageNumber'></span></div>
  </div>
</div>
<script>
  // Apps.page: $(".searchAreaHolder").insertAfter("#menu");
  document.getElementById('menu').after(document.querySelector('.searchAreaHolder'));
</script>
""")
print(out)
